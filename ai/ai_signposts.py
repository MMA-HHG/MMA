#!/usr/bin/env python3
"""Generate and verify the signposts of MMA's AI support.

Signposts are small generated files at each agent's standard paths that point to the
canonical AI-support files. Conventions: docs/ai/README.md, section 10.

Usage:
    python3 ai/ai_signposts.py           write all signposts and remove stale ones
    python3 ai/ai_signposts.py --check   verify only; exit status 1 on any difference

Needs Python 3.8 or later and PyYAML.
"""

import argparse
import json
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - reported to the user
    sys.exit("ai/ai_signposts.py needs PyYAML: python3 -m pip install pyyaml")

MANIFEST = "docs/ai/signposts.yml"
CODEOWNERS = ".github/CODEOWNERS"
MARKER = "Generated by ai/ai_signposts.py"
# Markers of earlier locations of this script, so that their files are still recognised.
LEGACY_MARKERS = ("Generated by tools/ai_signposts.py",)
HEADER = ("<!-- Generated by ai/ai_signposts.py from docs/ai/signposts.yml. "
          "Do not edit by hand. -->")
CORE_BEGIN = "# mma-core-begin"
CORE_END = "# mma-core-end"

# Where generated files may remain after an entity was removed; used to find stale ones.
GENERATED_GLOBS = [
    ".claude/skills/*/SKILL.md",
    ".agents/skills/*/SKILL.md",
    ".claude/rules/*.md",
    ".github/instructions/*.instructions.md",
    ".cursor/rules/*.mdc",
    "*/AGENTS.md",
    ".*/.gitignore",
]


def repo_root():
    return Path(__file__).resolve().parent.parent


def is_generated(text):
    """True if a text carries the marker of a generated file, current or legacy."""
    return any(marker in text for marker in (MARKER,) + LEGACY_MARKERS)


def split_frontmatter(text):
    """Return (front matter as dict or None, body) of a Markdown text."""
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ValueError("front matter is not closed by a line '---'")
    data = yaml.safe_load(text[4:end]) or {}
    if not isinstance(data, dict):
        raise ValueError("front matter is not a mapping")
    return data, text[end + 5:]


def load_manifest(root):
    data = yaml.safe_load((root / MANIFEST).read_text(encoding="utf-8")) or {}
    entries = data.get("signposts") or []
    if not isinstance(entries, list):
        raise ValueError(f"{MANIFEST}: 'signposts' must be a list")
    return entries


def core_paths(root):
    """Paths in the core block of .github/CODEOWNERS, as written there (e.g. '/CUPRAD/')."""
    path = root / CODEOWNERS
    if not path.is_file():
        return []
    inside, paths = False, []
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped == CORE_BEGIN:
            inside = True
        elif stripped == CORE_END:
            break
        elif inside and stripped and not stripped.startswith("#"):
            paths.append(stripped.split()[0])
    return paths


def core_globs(paths):
    """Repository-relative glob patterns for the core paths."""
    return [p.lstrip("/") + "**" if p.endswith("/") else p.lstrip("/") for p in paths]


def core_dirs(paths):
    return [p.strip("/") for p in paths if p.endswith("/")]


def canonical_skills(root):
    """Hand-written skills in .agents/skills, i.e. all whose status is not 'generated'."""
    base = root / ".agents" / "skills"
    skills = []
    if not base.is_dir():
        return skills
    for folder in sorted(p for p in base.iterdir() if p.is_dir()):
        skill_md = folder / "SKILL.md"
        if not skill_md.is_file():
            continue
        frontmatter, _ = split_frontmatter(skill_md.read_text(encoding="utf-8"))
        if not frontmatter:
            continue
        metadata = frontmatter.get("metadata") or {}
        if str(metadata.get("mma-status", "")) == "generated":
            continue
        skills.append({
            "name": str(frontmatter.get("name", folder.name)),
            "description": str(frontmatter.get("description", "")),
            "target": f".agents/skills/{folder.name}/SKILL.md",
            "workflow": False,
        })
    return skills


def workflows(root):
    base = root / "docs" / "ai" / "workflows"
    items = []
    if not base.is_dir():
        return items
    for path in sorted(base.glob("*.md")):
        frontmatter, _ = split_frontmatter(path.read_text(encoding="utf-8"))
        frontmatter = frontmatter or {}
        items.append({
            "name": path.stem,
            "description": str(frontmatter.get("description", "")),
            "track": str(frontmatter.get("mma-track", "")),
            "target": f"docs/ai/workflows/{path.name}",
        })
    return items


def quoted(value):
    """A YAML double-quoted scalar; JSON strings are valid YAML."""
    return json.dumps(value, ensure_ascii=False)


def skill_file(name, description, metadata, body):
    lines = ["---", f"name: {name}", f"description: {quoted(description)}", "metadata:"]
    lines += [f"  {key}: {quoted(value)}" for key, value in metadata.items()]
    lines += ["---", HEADER, "", body, ""]
    return "\n".join(lines)


def deep_merge(base, extra):
    merged = dict(base)
    for key, value in (extra or {}).items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def render(root):
    """Return {repository-relative path: expected content} for every signpost."""
    entries = load_manifest(root)
    paths = core_paths(root)
    globs = core_globs(paths)
    names = ", ".join(p.strip("/") for p in paths)
    core_rule = (
        f"These files belong to MMA's numerical core ({names}; see the core block in "
        "`.github/CODEOWNERS`). Before editing them during an operation or analysis task, "
        "state the transition to core development; then follow "
        "`docs/ai/workflows/modify-core.md` and the repository rules in `AGENTS.md`."
    )

    # Workflow signpost skills are needed by both 'workflow-skills' and 'pointer-skills'.
    workflow_skills = []
    for entry in entries:
        if entry.get("kind") == "workflow-skills":
            for wf in workflows(root):
                workflow_skills.append({
                    "name": f"mma-{wf['name']}",
                    "description": wf["description"],
                    "track": wf["track"],
                    "target": wf["target"],
                    "dir": entry.get("path", ".agents/skills"),
                    "workflow": True,
                })

    out = {}
    for entry in entries:
        kind, path = entry.get("kind"), entry.get("path")
        if kind == "import":
            # Only the import line, so that agents reading several instruction files
            # (GitHub Copilot reads CLAUDE.md too) get no content of its own.
            out[path] = f"@{entry.get('target', 'AGENTS.md')}\n"
        elif kind == "gemini-settings":
            settings = {"context": {"fileName": list(entry.get("context_files") or ["AGENTS.md"])}}
            settings = deep_merge(settings, entry.get("extra"))
            out[path] = json.dumps(settings, indent=2, ensure_ascii=False) + "\n"
        elif kind == "workflow-skills":
            for skill in workflow_skills:
                metadata = {
                    "mma-status": "generated",
                    "mma-entity": "workflow-signpost",
                    "mma-track": skill["track"],
                    "mma-signpost-for": skill["target"],
                }
                body = (f"This skill is a signpost for a workflow. Read `{skill['target']}` "
                        "and follow its route.")
                out[f"{skill['dir']}/{skill['name']}/SKILL.md"] = skill_file(
                    skill["name"], skill["description"], metadata, body)
        elif kind == "pointer-skills":
            for skill in canonical_skills(root) + workflow_skills:
                metadata = {
                    "mma-status": "generated",
                    "mma-entity": "signpost",
                    "mma-signpost-for": skill["target"],
                }
                if skill["workflow"]:
                    body = f"This is a signpost. Read `{skill['target']}` and follow its route."
                else:
                    folder = skill["target"].rsplit("/", 1)[0]
                    body = (f"This is a signpost. Read `{skill['target']}` and follow it; "
                            f"resolve its relative paths from `{folder}/`.")
                out[f"{path}/{skill['name']}/SKILL.md"] = skill_file(
                    skill["name"], skill["description"], metadata, body)
        elif kind == "scoped-rule":
            fmt = entry.get("format")
            if fmt == "claude-rule":
                frontmatter = "---\npaths:\n" + "".join(f"  - {quoted(g)}\n" for g in globs) + "---\n"
            elif fmt == "copilot-instructions":
                frontmatter = f"---\napplyTo: {quoted(','.join(globs))}\n---\n"
            elif fmt == "cursor-rule":
                frontmatter = (
                    "---\n"
                    f"description: {quoted('MMA numerical-core modules: what to do before editing them')}\n"
                    f"globs: {','.join(globs)}\n"
                    "alwaysApply: false\n"
                    "---\n")
            else:
                raise ValueError(f"{MANIFEST}: unknown scoped-rule format '{fmt}'")
            out[path] = f"{frontmatter}{HEADER}\n\n{core_rule}\n"
        elif kind == "nested-agents":
            filename = entry.get("file", "AGENTS.md")
            for folder in core_dirs(paths):
                out[f"{folder}/{filename}"] = (
                    f"{HEADER}\n\n# Numerical-core module\n\n"
                    "This directory is part of MMA's numerical core (see the core block in "
                    "`.github/CODEOWNERS`). Before editing it during an operation or analysis task, "
                    "state the transition to core development; then follow "
                    "`docs/ai/workflows/modify-core.md` and the repository rules in the root `AGENTS.md`.\n")
        elif kind == "ignore-file":
            lines = [f"# {MARKER} from {MANIFEST}. Do not edit by hand."]
            out[path] = "\n".join(lines + [str(p) for p in entry.get("patterns") or []]) + "\n"
        elif kind == "pointer-file":
            target = entry.get("target", "AGENTS.md")
            head = ""
            if entry.get("frontmatter"):
                head = "---\n" + yaml.safe_dump(entry["frontmatter"], sort_keys=False,
                                                allow_unicode=True) + "---\n"
            out[path] = f"{head}{HEADER}\n\nThis is a signpost. Read `{target}` and follow it.\n"
        else:
            raise ValueError(f"{MANIFEST}: unknown signpost kind '{kind}'")
    return out


def existing_generated(root):
    """Generated files currently present, recognised by their header."""
    found = set()
    for pattern in GENERATED_GLOBS:
        for path in root.glob(pattern):
            try:
                if is_generated(path.read_text(encoding="utf-8")[:4000]):
                    found.add(path.relative_to(root).as_posix())
            except (OSError, UnicodeDecodeError):
                continue
    return found


def unmanaged_keys(existing, expected, prefix=""):
    """Keys in an existing JSON document that the generated one would drop."""
    keys = []
    if isinstance(existing, dict):
        for key, value in existing.items():
            name = f"{prefix}{key}"
            if not isinstance(expected, dict) or key not in expected:
                keys.append(name)
            else:
                keys += unmanaged_keys(value, expected[key], name + ".")
    return keys


def json_conflict(path, content):
    """Settings in an existing JSON file that the manifest lacks, or None."""
    try:
        keys = unmanaged_keys(json.loads(path.read_text(encoding="utf-8")), json.loads(content))
    except ValueError:
        return "it is not valid JSON"
    return ", ".join(keys) if keys else None


def check(root):
    """Return a list of problems; empty when all signposts are up to date."""
    try:
        expected = render(root)
    except (OSError, ValueError, yaml.YAMLError) as exc:
        return [f"cannot render signposts: {exc}"]
    problems = []
    for rel, content in sorted(expected.items()):
        path = root / rel
        if not path.is_file():
            problems.append(f"missing signpost: {rel}")
        elif path.read_text(encoding="utf-8") != content:
            if rel.endswith("/SKILL.md") and not is_generated(path.read_text(encoding="utf-8")):
                problems.append(f"hand-written skill in the place of a signpost; rename it: {rel}")
            elif rel.endswith(".json") and json_conflict(path, content):
                problems.append(f"{rel} holds settings that the manifest lacks ({json_conflict(path, content)}); "
                                "move them under 'extra' in its entry of docs/ai/signposts.yml")
            else:
                problems.append(f"signpost differs from the manifest (edited by hand or stale): {rel}")
    for rel in sorted(existing_generated(root) - set(expected)):
        problems.append(f"stale generated file: {rel}")
    return problems


def write(root):
    """Write all signposts and remove stale generated files; return a list of actions."""
    expected = render(root)
    actions = []
    for rel, content in sorted(expected.items()):
        path = root / rel
        if path.is_file():
            existing = path.read_text(encoding="utf-8")
            if existing == content:
                continue
            if rel.endswith("/SKILL.md") and not is_generated(existing):
                raise ValueError(f"{rel} is a hand-written skill in the place of a signpost; "
                                 "rename the skill or the workflow")
            if rel.endswith(".json") and json_conflict(path, content):
                raise ValueError(f"{rel} holds settings that the manifest lacks "
                                 f"({json_conflict(path, content)}); move them under 'extra' in its "
                                 "entry of docs/ai/signposts.yml, then run the generator again")
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        actions.append(f"wrote   {rel}")
    for rel in sorted(existing_generated(root) - set(expected)):
        path = root / rel
        path.unlink()
        actions.append(f"removed {rel}")
        parent = path.parent
        if parent != root and not any(parent.iterdir()):
            parent.rmdir()
    return actions


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate and verify MMA's signposts.")
    parser.add_argument("--check", action="store_true",
                        help="verify only; exit status 1 on any difference")
    parser.add_argument("--root", type=Path, default=repo_root(),
                        help="repository root (default: the parent of ai/)")
    args = parser.parse_args(argv)
    root = args.root.resolve()

    if args.check:
        problems = check(root)
        for problem in problems:
            print(f"ERROR   [S6] {problem}")
        if problems:
            print("Run 'python3 ai/ai_signposts.py' to regenerate the signposts.")
            return 1
        print("Signposts are up to date.")
        return 0

    try:
        actions = write(root)
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"ERROR   cannot write signposts: {exc}")
        return 1
    for action in actions:
        print(action)
    print(f"Signposts written ({len(actions)} change(s)).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
